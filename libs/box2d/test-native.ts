// Opt-in low-level smoke checks. Keep temporary references off the global heap roots.
function check(condition: boolean, message: string) {
    if (!condition) control.fail(message)
}
function runNativeSmokeTests() {
    const physicsWorld = box2dNative.createWorld()
    const groundBody = box2dNative.createBody(physicsWorld, box2d.BodyType.Static, 0, 5)
    const groundShape = box2dNative.createBoxShape(10, 0.5)
    const groundFixture = box2dNative.createFixture(groundBody, groundShape, 0)
    const ballBody = box2dNative.createBody(physicsWorld, box2d.BodyType.Dynamic)
    const ballShape = box2dNative.createCircleShape(0.5)
    const ballFixture = box2dNative.createFixture(ballBody, ballShape)
    box2dNative.destroyShape(groundShape)
    box2dNative.destroyShape(ballShape)
    for (let i = 0; i < 240; i++) {
        box2dNative.step(physicsWorld)
    }
    check(Math.abs(box2dNative.getBodyState(ballBody)[box2d.BodyState.Y] - 4) < 0.02, "ball rests on ground")
    const transform = [0, 0, 0]
    box2dNative.readBodyTransform(ballBody, transform)
    check(Math.abs(transform[1] - 4) < 0.02, "reusable body transform")
    const vertices = [0, 0, 0, 0, 0, 0, 0, 0]
    box2dNative.readBodyBoxVertices(groundBody, [1, 0.5, 0, 0], [8, 80, 60], vertices)
    check(vertices[0] == 72 && vertices[1] == 96 && vertices[4] == 88 && vertices[5] == 104, "integer box vertices")
    check(box2dNative.getContacts(physicsWorld).length == 2, "touching fixtures")
    check(box2dNative.rayCast(physicsWorld, 0, 0, 0, 10)[box2d.RayHit.Fixture] == ballFixture, "closest ray hit")
    check(box2dNative.queryAABB(physicsWorld, -1, 3, 1, 6).length == 2, "query fixtures")
    check(box2dNative.testPoint(ballFixture, 0, 4), "point in ball")
    check(box2dNative.getFixtureBody(ballFixture) == ballBody, "fixture owner")
    box2dNative.setGravity(physicsWorld, 0, 0)
    box2dNative.setWorldSleepingAllowed(physicsWorld, false)
    box2dNative.setBodyType(ballBody, box2d.BodyType.Dynamic)
    box2dNative.setTransform(ballBody, 0, 0, 0)
    box2dNative.setLinearVelocity(ballBody, 0.25, 0.5)
    box2dNative.setAngularVelocity(ballBody, 0.75)
    box2dNative.setDamping(ballBody, 0.1, 0.2)
    box2dNative.setGravityScale(ballBody, 0)
    box2dNative.setBodyFlag(ballBody, box2d.BodyFlag.Bullet, true)
    check(box2dNative.getBodyFlag(ballBody, box2d.BodyFlag.Bullet), "bullet flag")
    box2dNative.applyForce(ballBody, 1, 0, 0, 0)
    box2dNative.applyForceToCenter(ballBody, 0, 1)
    box2dNative.applyLinearImpulse(ballBody, 0.5, 0, 0, 0)
    box2dNative.applyLinearImpulseToCenter(ballBody, 0, 0.5)
    box2dNative.applyTorque(ballBody, 0.1)
    box2dNative.applyAngularImpulse(ballBody, 0.2)
    const point = box2dNative.getWorldPoint(ballBody, 1, 2)
    const localPoint = box2dNative.getLocalPoint(ballBody, point[0], point[1])
    check(Math.abs(localPoint[0] - 1) < 0.001, "local coordinate")
    box2dNative.setFixtureMaterial(ballFixture, 2, 0.3, 0.4)
    box2dNative.setFixtureSensor(ballFixture, true)
    box2dNative.setFixtureFilter(ballFixture)
    const polygonShape = box2dNative.createPolygonShape([-1, -1, 1, -1, 0, 1])
    const edgeShape = box2dNative.createEdgeShape(-1, 0, 1, 0)
    const chainShape = box2dNative.createChainShape([-1, -1, 1, -1, 1, 1], false)
    box2dNative.destroyShape(polygonShape)
    box2dNative.destroyShape(edgeShape)
    box2dNative.destroyShape(chainShape)
    const distanceJoint = box2dNative.createDistanceJoint(groundBody, ballBody, 0, 5, 0, 0)
    box2dNative.setDistanceJoint(distanceJoint, 5, 4, 6, 2, 0.5)
    box2dNative.destroyJoint(distanceJoint)
    const hingeJoint = box2dNative.createRevoluteJoint(groundBody, ballBody, 0, 0)
    box2dNative.setRevoluteJointMotor(hingeJoint, true, 0.5, 1)
    box2dNative.setRevoluteJointLimits(hingeJoint, true, -0.5, 0.5)
    const mouseJoint = box2dNative.createMouseJoint(groundBody, ballBody, 0, 0, 100, 10, 1)
    box2dNative.setMouseJointTarget(mouseJoint, 1, 1)
    box2dNative.destroyJoint(mouseJoint)
    box2dNative.destroyFixture(groundFixture)
    box2dNative.destroyBody(groundBody)
    check(!box2dNative.isValid(hingeJoint), "body destruction invalidates joints")
    box2dNative.destroyWorld(physicsWorld)
    check(!box2dNative.isValid(ballBody) && !box2dNative.isValid(ballFixture), "world destruction invalidates children")
    console.log("Box2D native smoke test passed")
}
